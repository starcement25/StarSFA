package com.forcepower.acedns.bean;

public class RouteDetails {
    String routeCode = "";
    String routeName = "";
    String replacingRouteCode = "";
    String distributorCode = "";
    String employeeCode = "";
    String acedns = "";
    String visitDay = "";
    String branch_code = "";

    public String getDistributorCode() {
        return distributorCode;
    }

    public void setDistributorCode(String distributorCode) {
        this.distributorCode = distributorCode;
    }

    public String getEmployeeCode() {
        return employeeCode;
    }

    public void setEmployeeCode(String employeeCode) {
        this.employeeCode = employeeCode;
    }

    public String getReplacingRouteCode() {
        return replacingRouteCode;
    }

    public void setReplacingRouteCode(String replacingRouteCode) {
        this.replacingRouteCode = replacingRouteCode;
    }

    public String getRouteCode() {
        return routeCode;
    }

    public void setRouteCode(String routeCode) {
        this.routeCode = routeCode;
    }

    public String getRouteName() {
        return routeName;
    }

    public void setRouteName(String routeName) {
        this.routeName = routeName;
    }

    public String getacedns() {
        return acedns;
    }

    public void setacedns(String acedns) {
        this.acedns = acedns;
    }

    public String getvisitDay() {
        return visitDay;
    }

    public void setvisitDay(String visitDay) {
        this.visitDay = visitDay;
    }

    public String getbranch_code() {
        return branch_code;
    }

    public void setbranch_code(String branch_code) {
        this.branch_code = branch_code;
    }
}
