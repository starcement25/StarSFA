package com.forcepower.acedns.bean;

public class ConversionDataDetails {
    String prod_code = "";
    String mapped_prod_code = "";
    String is_flash = "";
    String flash_name = "";

    public String getprod_code() {
        return prod_code;
    }

    public void setprod_code(String prod_code) {
        this.prod_code = prod_code;
    }

    public String getmapped_prod_code() {
        return mapped_prod_code;
    }

    public void setmapped_prod_code(String mapped_prod_code) {
        this.mapped_prod_code = mapped_prod_code;
    }

    public String getis_flash() {
        return is_flash;
    }

    public void setis_flash(String is_flash) {
        this.is_flash = is_flash;
    }

    public String getflash_name() {
        return flash_name;
    }

    public void setflash_name(String flash_name) {
        this.flash_name = flash_name;
    }
}
