package com.forcepower.acedns.bean;

public class WholeSaleInfo {
    String wholesaleID = "";
    String customerCode = "";
    String debitnotCollected = "";
    String lastDebitNoteReceived = "";
    String closingStockValue = "";
    String logBook = "";

    public String getWholesaleID() {
        return wholesaleID;
    }

    public void setWholesaleID(String wholesaleID) {
        this.wholesaleID = wholesaleID;
    }

    public String getCustomerCode() {
        return customerCode;
    }

    public void setCustomerCode(String customerCode) {
        this.customerCode = customerCode;
    }

    public String getDebitnotCollected() {
        return debitnotCollected;
    }

    public void setDebitnotCollected(String debitnotCollected) {
        this.debitnotCollected = debitnotCollected;
    }

    public String getLastDebitNoteReceived() {
        return lastDebitNoteReceived;
    }

    public void setLastDebitNoteReceived(String lastDebitNoteReceived) {
        this.lastDebitNoteReceived = lastDebitNoteReceived;
    }

    public String getClosingStockValue() {
        return closingStockValue;
    }

    public void setClosingStockValue(String closingStockValue) {
        this.closingStockValue = closingStockValue;
    }

    public String getLogBook() {
        return logBook;
    }

    public void setLogBook(String logBook) {
        this.logBook = logBook;
    }

}
