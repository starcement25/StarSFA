package com.forcepower.acedns.bean;

public class TentProduct {
    
    String tent_form_id;
    String product;
    String brand;
    String life_of_product;
    String mobile_no;

    public String getTent_form_id() {
        return tent_form_id;
    }

    public void setTent_form_id(String tent_form_id) {
        this.tent_form_id = tent_form_id;
    }

    public String getProduct() {
        return product;
    }

    public void setProduct(String product) {
        this.product = product;
    }

    public String getBrand() {
        return brand;
    }

    public void setBrand(String brand) {
        this.brand = brand;
    }

    public String getLife_of_product() {
        return life_of_product;
    }

    public void setLife_of_product(String life_of_product) {
        this.life_of_product = life_of_product;
    }

    public String getMobile_no() {
        return mobile_no;
    }

    public void setMobile_no(String mobile_no) {
        this.mobile_no = mobile_no;
    }
}
