package com.forcepower.acedns.bean;


public class SplashScreenDetails {

    String attendanceToday = "";
    String totalSaleMtd = "";
    String totalSaleFtd = "";
    String closingStock = "";
    String zeroOutlet = "";

    public String getattendanceToday() {
        return attendanceToday;
    }

    public void setattendanceToday(String attendanceToday) {
        this.attendanceToday = attendanceToday;
    }

    public String gettotalSaleMtd() {
        return totalSaleMtd;
    }

    public void settotalSaleMtd(String totalSaleMtd) {
        this.totalSaleMtd = totalSaleMtd;
    }
    public String gettotalSaleFtd() {
        return totalSaleFtd;
    }

    public void settotalSaleFtd(String totalSaleFtd) {
        this.totalSaleFtd = totalSaleFtd;
    }

    public String getclosingStock() {
        return closingStock;
    }

    public void setclosingStock(String closingStock) {
        this.closingStock = closingStock;
    }
    public String getzeroOutlet() {
        return zeroOutlet;
    }

    public void setzeroOutlet(String zeroOutlet) {
        this.zeroOutlet = zeroOutlet;
    }
}
