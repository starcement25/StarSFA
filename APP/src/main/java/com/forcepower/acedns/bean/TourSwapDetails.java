package com.forcepower.acedns.bean;

public class TourSwapDetails {
    String transactionId = "";
    String empCode = "";
    String actualTourDay = "";
    String deviateTourDay = "";
    String swapDateActual = "";
    String swapDateDeviate = "";
    String flag = "";

    public String getTransactionId() {
        return transactionId;
    }

    public void setTransactionId(String transactionId) {
        this.transactionId = transactionId;
    }

    public String getEmpCode() {
        return empCode;
    }

    public void setEmpCode(String empCode) {
        this.empCode = empCode;
    }

    public String getActualTourDay() {
        return actualTourDay;
    }

    public void setActualTourDay(String actualTourDay) {
        this.actualTourDay = actualTourDay;
    }

    public String getDeviateTourDay() {
        return deviateTourDay;
    }

    public void setDeviateTourDay(String deviateTourDay) {
        this.deviateTourDay = deviateTourDay;
    }

    public String getSwapDateActual() {
        return swapDateActual;
    }

    public void setSwapDateActual(String swapDateActual) {
        this.swapDateActual = swapDateActual;
    }

    public String getSwapDateDeviate() {
        return swapDateDeviate;
    }

    public void setSwapDateDeviate(String swapDateDeviate) {
        this.swapDateDeviate = swapDateDeviate;
    }

    public String getFlag() {
        return flag;
    }

    public void setFlag(String flag) {
        this.flag = flag;
    }


}
